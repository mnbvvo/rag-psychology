# 低相关时的补充说明（仅「RAG 开启且检索为空」时动态插入，要求模型如实说明而非编造）
LOW_RELEVANCE_NOTE = (
    "\n【重要】本次未检索到足够相关的参考资料。"
    "若无法直接、有据地回答，请明确说明“我目前没有足够的信息来回答这个问题”，不要编造内容。"
)

# 输出长度硬约束：由 rag_core._build_messages 作为**独立 system 消息**发出，
# 插在历史消息之后、当前问题之前——**不拼进 system prompt 字符串**（见 rag_core）。
# 背景（2026-09-10）：小程序通道注入长期记忆段 + 家庭档案段后，ACTIVE_PROMPT
# 第七条的字数要求被挤到 prompt 中段、权重被稀释，实测长尾回复到 260 汉字；
# 且 system 之后仍压着最多 MEMORY_RECENT_ROUNDS 轮历史，锚定效应会抵消指令。
# 置于整个请求最末可让长度指令保持最高优先级；不涉及截断（max_tokens 仍为 4096）。
OUTPUT_LENGTH_RULE = """
【回复长度硬约束：优先级最高，覆盖前面任何让你展开或写长的要求】
每轮回复控制在 3-5 句话、不超过 180 个汉字。
上面注入的家庭档案和历史记录只用于你理解用户，不要在回复里复述、罗列，也不要据此展开分析——除非用户明确要求你回顾或复述。
写完后自查一遍，超了就删掉解释和分析部分，只留一句承接，加一个主要理解或一个具体办法。
"""


def build_system_prompt(
    context_text: str = "",
    low_relevance: bool = False,
) -> str:
    """组装最终系统提示词：ACTIVE_PROMPT + 参考资料({context})。

    context_text：检索到的知识卡片拼接文本（RAG 开启且有结果时）；
    low_relevance：是否追加「未检索到足够资料」说明（由 rag_core 按
    「RAG 开启且检索为空」计算后传入；纯对话模式为 False，不追加）。
    """
    base = ACTIVE_PROMPT

    # 有参考资料时正常拼接；检索为空时**不要**输出 {context} 字面占位——
    # 它会触发 ChatPromptTemplate 的模板变量解析（缺 context 变量报 KeyError），
    # 且对 LLM 也无意义，由 LOW_RELEVANCE_NOTE 负责向模型说明"无参考资料"。
    ref = f"参考资料:\n{context_text}" if context_text else ""
    if low_relevance:
        ref = (LOW_RELEVANCE_NOTE + "\n\n" + ref).rstrip() if ref else LOW_RELEVANCE_NOTE
    if base and ref:
        return base + "\n\n" + ref
    return base or ref
